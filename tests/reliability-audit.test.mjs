import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'prospector-reliability-'));
process.env.PROSPECTOR_DATA_DIR=dir;
process.env.WA_AKG_SESSION_ID='reliability-session';
const d=await import('../dashboard/db.mjs');
await import('../dashboard/prospecting-queue.mjs');
const {bindLeadSession}=await import('../dashboard/waakg-session-registry.mjs');
const {holdInboundDuringGreeting,reconcileHeldInbound,heldInboundSummary,recordInboundTranscript}=await import('../dashboard/waakg-bridge.mjs');
const {queueHealth}=await import('../dashboard/queue-health.mjs');
const {kanbanSnapshot}=await import('../dashboard/kanban.mjs');
const sid='reliability-session';
const at=new Date('2026-11-25T14:00:00Z');
const stamp=at.toISOString();
d.setSetting('paused',false);
d.setSetting('autonomous_outreach_enabled',true);
d.setSetting('daily_limit',1);
const lead=d.addLead({business:'Synthetic audit fixture',phone:'5515999912345',source:'TEST'}).lead;
const jid=lead.phone+'@s.whatsapp.net',greeting=d.id(),batch=d.id();
bindLeadSession(lead.id,sid);
d.run("INSERT INTO prospecting_batches(id,status,created_at,updated_at,origin) VALUES(?,?,?,?,?)",batch,'ACTIVE',stamp,stamp,'AUTONOMOUS');
d.run("INSERT INTO prospecting_batch_items(id,batch_id,lead_id,phone,status,attempt_at,created_at) VALUES(?,?,?,?,?,?,?)",greeting,batch,lead.id,lead.phone,'SENDING',stamp,stamp);
d.run("INSERT INTO prospecting_text_receipts(lead_id,greeting_id,kind,session_id,jid,attempted_at,status) VALUES(?,?,?,?,?,?,?)",lead.id,greeting,'GREETING',sid,jid,stamp,'UNKNOWN');
test('uncertain greeting retains only matching routed text and does not grant consent or start a send',()=>{
 assert.equal(holdInboundDuringGreeting({sessionId:sid,jid:'5515999912346@s.whatsapp.net',providerId:sid+':unrelated',text:'Oi'}),false);
 const event={sessionId:sid,jid,providerId:sid+':early-reply',text:'Oi, tudo bem?'};
 assert.equal(holdInboundDuringGreeting(event),true);
 assert.equal(holdInboundDuringGreeting(event),true);
 assert.equal(heldInboundSummary().counts.WAITING_PROOF,1);
 assert.equal(reconcileHeldInbound().recovered,0);
 assert.equal(d.one('SELECT COUNT(*) n FROM waakg_inbox').n,0);
 assert.equal(d.one('SELECT contact_permission FROM leads WHERE id=?',lead.id).contact_permission,0);
});
test('diagnostic reports shared daily cap even for an uncertain reserved greeting',()=>{
 const health=queueHealth({at,waStatus:'CONNECTED'});
 assert.equal(health.initialToday.limit,1);
 assert.equal(health.initialToday.counted,1);
 assert.equal(health.reason,'DAILY_CAP_REACHED');
});
test('verified greeting restores exactly one original inbound record without sending',()=>{
 const thread=d.getThread(lead.id,jid);
 d.addMessage({threadId:thread.id,providerId:'prospect-queue:'+greeting,direction:'out',body:'Oi!',status:'sent'});
 d.run("UPDATE prospecting_batch_items SET status='SENT' WHERE id=?",greeting);
 d.run("UPDATE prospecting_text_receipts SET status='SENT',provider_id='ORIGINAL_GREETING' WHERE greeting_id=?",greeting);
 d.run("INSERT INTO prospecting_introductions(lead_id,phone,session_id,greeting_id,stage,created_at,updated_at) VALUES(?,?,?,?,?,?,?)",lead.id,lead.phone,sid,greeting,'GREETING_SENT',d.now(),d.now());
 assert.equal(reconcileHeldInbound().recovered,1);
 assert.equal(reconcileHeldInbound().recovered,0);
 assert.equal(d.one('SELECT COUNT(*) n FROM waakg_inbox WHERE lead_id=?',lead.id).n,1);
 assert.equal(d.one('SELECT stage FROM prospecting_introductions WHERE lead_id=?',lead.id).stage,'WAITING');
});
test('new inbound from an interested lead preserves the commercial stage and human ownership',()=>{
 d.run("UPDATE leads SET stage='INTERESTED' WHERE id=?",lead.id);
 d.run("UPDATE threads SET manual_takeover=1 WHERE lead_id=?",lead.id);
 const r=recordInboundTranscript({sessionId:sid,jid,unique:sid+':interested-followup',content:'Obrigado, vou conferir'});
 assert.equal(r.body.processed,true);
 assert.equal(d.one('SELECT stage FROM leads WHERE id=?',lead.id).stage,'INTERESTED');
 assert.equal(d.one('SELECT state FROM waakg_inbox WHERE provider_id=?',sid+':interested-followup').state,'HUMAN');
 assert.equal(kanbanSnapshot().counts.interested,1);
});
test.after(()=>{d.db.close();fs.rmSync(dir,{recursive:true,force:true});});
