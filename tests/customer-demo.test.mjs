import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {openPlatformStore} from '../dashboard/platform-store.mjs';
import {workerEnvironment} from '../dashboard/platform.mjs';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'prospector-client-demo-'));
test('creates one real isolated demo customer, 100 fictitious credits, and cannot bill',()=>{
 const store=openPlatformStore(dir);
 const a=store.ensureDemoClient(),b=store.ensureDemoClient();
 assert.equal(a.id,b.id);
 assert.equal(a.demo,true);
 assert.equal(a.internal,false);
 assert.equal(a.balance,100);
 assert.equal(a.available,100);
 assert.equal(a.trial,null,'demo never claims a real CPF identity check');
 assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM clients WHERE is_demo=1').get().n,1);
 assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM credit_events WHERE client_id=?').get(a.id).n,1,'idempotent credit seed');
 assert.throws(()=>store.requestCredits(a.id,'dia1','12345678-1234-4123-8123-123456789abc'),/demonstração/i);
 const env=workerEnvironment(store.get(a.id),3020);
 assert.equal(env.PROSPECTOR_DEMO_MODE,'true');
 assert.equal(env.PROSPECTOR_AUTONOMOUS_OUTREACH_OPT_IN,'false');
 assert.equal(env.AI_CONVERSATION_AUTOSEND,'false');
 assert.equal(env.PROSPECTOR_INBOUND_AUTOREPLY_ENABLED,'false');
 assert.equal(env.WA_AKG_API_KEY,undefined);
 assert.equal(env.WA_AKG_ADMIN_PASSWORD,undefined);
 store.db.close();
});
test('demo account persists after process restart without extra credits',()=>{
 const store=openPlatformStore(dir);
 const old=store.ensureDemoClient();
 assert.equal(old.balance,100);
 const reopened=store.ensureDemoClient();
 assert.equal(reopened.id,old.id);
 assert.equal(store.balance(old.id),100);
 store.db.close();
});
test.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
