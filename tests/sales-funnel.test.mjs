import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
process.env.PROSPECTOR_DATA_DIR=fs.mkdtempSync(path.join(os.tmpdir(),'prospector-campaign-'));
const db=await import('../dashboard/db.mjs');
const runtime=await import('../dashboard/runtime.mjs');
const cadence=await import('../dashboard/contact-cadence.mjs');
const offer=await import('../dashboard/campaign-rules.mjs');
const routing=await import('../dashboard/automation-router.mjs');
const intent=await import('../dashboard/classifier.mjs');
test('funil: áudio após resposta e 60 segundos; vídeo após áudio',async()=>{
 const audio='audio-test',video='video-test',at=db.now();
 db.run("INSERT INTO media(id,name,kind,mime,filename,bytes,created_at) VALUES(?,?,?,?,?,?,?)",audio,'Oferta de exemplo','audio','audio/ogg','offer.ogg',12,at);
 db.run("INSERT INTO media(id,name,kind,mime,filename,bytes,created_at) VALUES(?,?,?,?,?,?,?)",video,'Exemplo de site','video','video/mp4','demo.mp4',12,at);
 const lead=db.addLead({business:'Empresa Fluxo de Teste',phone:'5515999776655',contact_permission:true,source:'TEST'}).lead;
 db.audit('CONSENT_UPDATED',lead.id,{permitted:true,evidence:'Consentimento documentado no teste'});
 const steps=offer.proposedFlow({audioId:audio,videoId:video,intro:'Olá, {{business_name}}! Posso apresentar uma oferta da Consecom?'});
 assert.deepEqual(steps.map(x=>x.type),['message','wait_reply','delay','audio','delay','video','wait_reply','end']);
 const id=runtime.saveWorkflow({name:'Campanha Teste',segments:[],enabled:true,steps});
 const execution=runtime.startWorkflow(lead.id,id);
 runtime.drive(execution);
 let jobs=db.all('SELECT * FROM jobs WHERE lead_id=?',lead.id);
 assert.equal(jobs.length,1);assert.equal(jobs[0].type,'message');
 db.run("UPDATE jobs SET status='SENT' WHERE id=?",jobs[0].id);
 db.run("UPDATE executions SET state='ACTIVE' WHERE id=?",execution);
 runtime.drive(execution);
 assert.equal(db.one('SELECT state FROM executions WHERE id=?',execution).state,'WAIT_REPLY');
 await runtime.incoming({key:{remoteJid:'5515999776655@s.whatsapp.net',id:'reply-1'},pushName:'Cliente Teste',message:{conversation:'Oi, pode falar'}});
 const current=db.one('SELECT * FROM executions WHERE id=?',execution);
 assert.equal(current.state,'WAIT_DELAY');
 assert.ok(Date.parse(current.wake_at)-Date.now()>55000);
 assert.equal(db.all('SELECT * FROM jobs WHERE lead_id=?',lead.id).length,1);
 db.run("UPDATE executions SET state='ACTIVE' WHERE id=?",execution);
 runtime.drive(execution);
 const audioJob=db.one("SELECT * FROM jobs WHERE lead_id=? AND type='audio'",lead.id);
 assert.ok(audioJob);
 assert.equal(audioJob.media_id,audio);
 db.run("UPDATE jobs SET status='SENT' WHERE id=?",audioJob.id);
 db.run("UPDATE executions SET state='ACTIVE' WHERE id=?",execution);runtime.drive(execution);
 assert.equal(db.one('SELECT state FROM executions WHERE id=?',execution).state,'WAIT_DELAY');
 db.run("UPDATE executions SET state='ACTIVE' WHERE id=?",execution);runtime.drive(execution);
 assert.equal(db.one("SELECT media_id FROM jobs WHERE lead_id=? AND type='video'",lead.id)?.media_id,video);
 await runtime.incoming({key:{remoteJid:'5515999776655@s.whatsapp.net',id:'reply-2'},message:{conversation:'Tenho interesse, quanto custa?'}});
 assert.equal(db.one('SELECT stage FROM leads WHERE id=?',lead.id).stage,'INTERESTED');
 assert.equal(db.one('SELECT manual_takeover FROM threads WHERE lead_id=?',lead.id).manual_takeover,1);
 assert.equal(db.one("SELECT COUNT(*) c FROM owner_notices WHERE lead_id=?",lead.id).c,1);
 await runtime.incoming({key:{remoteJid:'5515999776655@s.whatsapp.net',id:'reply-3'},message:{conversation:'quero saber mais'}});
 assert.equal(db.one("SELECT COUNT(*) c FROM owner_notices WHERE lead_id=?",lead.id).c,1);
});
test('histórico de três meses de calendário e promoção não expirada',()=>{
 const start='2026-07-01T12:00:00.000Z',end=cadence.nextEligible(start);
 assert.equal(end,'2026-10-01T12:00:00.000Z');
 assert.equal(cadence.allowedToRecontact({phone:'5515999887766',contact_permission:1,stage:'REPLIED',next_contact_at:end},Date.parse(end)),true);
 assert.equal(cadence.allowedToRecontact({phone:'5515999887766',contact_permission:1,stage:'NO_INTEREST',next_contact_at:end},Date.parse(end)),true);
 assert.equal(offer.isOfferActive('2026-10-18',Date.parse('2026-10-18T20:00:00-03:00')),true);
 assert.equal(offer.isOfferActive('2026-10-18',Date.parse('2026-10-19T00:00:00-03:00')),false);
});

test('primeira resposta: cumprimento mantém espera; aceite posterior libera apresentação',async()=>{
 assert.equal(intent.classify('Oi, pode falar').intent,'NEUTRAL');
 assert.equal(routing.evaluateDecision('Oi, pode falar').decision,'YES');
 assert.equal(routing.evaluateDecision('Oi').decision,'REVIEW');
 const lead=db.addLead({business:'Teste Cumprimento',phone:'5515999889900',contact_permission:true,source:'TEST'}).lead;
 db.audit('CONSENT_UPDATED',lead.id,{permitted:true,evidence:'Consentimento documentado no teste'});
 const workflow=runtime.saveWorkflow({name:'Campanha Saudação Teste',enabled:true,steps:offer.proposedFlow({audioId:'audio-test',videoId:'video-test'})});
 const ex=runtime.startWorkflow(lead.id,workflow);runtime.drive(ex);
 db.run("UPDATE jobs SET status='SENT' WHERE lead_id=?",lead.id);
 db.run("UPDATE executions SET state='ACTIVE' WHERE id=?",ex);runtime.drive(ex);
 assert.equal(db.one('SELECT state FROM executions WHERE id=?',ex).state,'WAIT_REPLY');
 await runtime.incoming({key:{remoteJid:'5515999889900@s.whatsapp.net',id:'isolated-hi'},message:{conversation:'Oi'}});
 assert.equal(db.one('SELECT state FROM executions WHERE id=?',ex).state,'WAIT_REPLY');
 assert.equal(db.one("SELECT COUNT(*) n FROM jobs WHERE lead_id=? AND type='audio'",lead.id).n,0);
 await runtime.incoming({key:{remoteJid:'5515999889900@s.whatsapp.net',id:'later-yes'},message:{conversation:'Pode mandar'}});
 assert.equal(db.one('SELECT state FROM executions WHERE id=?',ex).state,'WAIT_DELAY');
});
