import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
const dir=fs.mkdtempSync(os.tmpdir()+'/operator-outreach-');
process.env.PROSPECTOR_DATA_DIR=dir;
const db=await import('../dashboard/db.mjs');
const queue=await import('../dashboard/prospecting-queue.mjs');
test('operator selection queues more than 100 public businesses without creating consent',()=>{
 const ids=Array.from({length:105},(_,i)=>db.addLead({business:'Public '+i,phone:'1198'+String(i).padStart(7,'0'),source:'MANUAL'}).lead.id);
 const result=queue.enqueueApprovedApproaches({leadIds:ids,approve:true,operatorApproved:true});
 assert.equal(result.status,202);assert.equal(result.body.queued,105);
 assert.equal(db.one('SELECT COUNT(*) n FROM leads WHERE contact_permission=1').n,0);
 assert.equal(db.one("SELECT COUNT(*) n FROM audit WHERE action='CONSENT_UPDATED'").n,0);
 queue.cancelApproachQueue();
});
test('the selected offer is stored with the outreach cycle rather than guessed from company names',async()=>{
 const auth=await import('../dashboard/operator-outreach.mjs');
 const lead=db.addLead({business:'Oferta corporativa',phone:'11981111222'}).lead;
 assert.equal(queue.enqueueApprovedApproaches({leadIds:[lead.id],approve:true,operatorApproved:true,offerType:'corporate'}).status,202);
 assert.equal(auth.operatorOffer(lead.id),'corporate');queue.cancelApproachQueue();
});
test('current cycle needs an actual incoming reply and cancellation cannot become historical permission',async()=>{
 const auth=await import('../dashboard/operator-outreach.mjs');
 const l=db.addLead({business:'Reply Co',phone:'11989999999',source:'MANUAL'}).lead;
 assert.equal(queue.enqueueApprovedApproaches({leadIds:[l.id,l.id],approve:true,operatorApproved:true}).body.queued,1);
 assert.equal(auth.operatorSelected(l.id),true);assert.equal(auth.conversationAuthorized(l.id),false);
 const send=async()=>({status:true});
 assert.equal((await queue.tickApproachQueue({getWaStatus:async()=>({connected:true}),getSession:()=> 'synthetic',send})).status,'SENT');
 assert.equal(auth.conversationAuthorized(l.id),false);
 const thread=db.getThread(l.id,l.phone+'@s.whatsapp.net');
 db.addMessage({threadId:thread.id,providerId:'in-current',direction:'in',body:'Oi',status:'received'});
 assert.equal(auth.conversationAuthorized(l.id),true);
 db.run('UPDATE threads SET manual_takeover=1 WHERE id=?',thread.id);
 assert.equal(auth.conversationAuthorized(l.id),false);
 assert.equal(auth.conversationAuthorized(l.id,{ignoreTakeover:true}),true);
 const handoff=await import('../dashboard/conversation-handoff.mjs');
 process.env.GROQ_API_KEY='synthetic';
 process.env.WA_AKG_SESSION_ID='synthetic';
 db.run("UPDATE prospecting_introductions SET stage='CONVERSING' WHERE lead_id=?",l.id);
 assert.equal(handoff.conversationHandoffStatus(thread.id).canDeliverToAi,true);
 assert.equal((await handoff.changeConversationHandoff({chatId:thread.id,manual:false})).status,200);
 db.run('UPDATE threads SET manual_takeover=0 WHERE id=?',thread.id);
 await queue.tickApproachQueue({send});
 db.run("UPDATE leads SET stage='DISCOVERED' WHERE id=?",l.id);
 db.run("UPDATE messages SET at='2020-01-01' WHERE thread_id=?",thread.id);
 db.run("UPDATE prospecting_batch_items SET attempt_at='2020-01-01' WHERE lead_id=?",l.id);
 db.run("UPDATE initial_contacts SET created_at='2020-01-01' WHERE lead_id=?",l.id);
 assert.equal(queue.enqueueApprovedApproaches({leadIds:[l.id],approve:true}).status,403);
 assert.equal(queue.enqueueApprovedApproaches({leadIds:[l.id],approve:true,operatorApproved:true}).status,202);
 assert.equal(auth.conversationAuthorized(l.id),false);
 queue.cancelApproachQueue();assert.equal(auth.operatorSelected(l.id),false);
});
test('operator approval cannot bypass owner, client, optout or human takeover',()=>{
 const cases=Array.from({length:4},(_,i)=>db.addLead({business:'Blocked '+i,phone:'1198777777'+i,source:'MANUAL'}).lead);
 process.env.PROSPECTOR_OWNER_PHONE=cases[0].phone;
 db.run("INSERT INTO contact_relationships(phone,kind,evidence,source,updated_at) VALUES(?,'EXISTING_CLIENT','verified customer','OPERATOR',?)",cases[1].phone,db.now());
 db.run('INSERT INTO suppressions(phone,reason,created_at) VALUES(?,?,?)',cases[2].phone,'optout',db.now());
 const t=db.getThread(cases[3].id,cases[3].phone+'@s.whatsapp.net');db.run('UPDATE threads SET manual_takeover=1 WHERE id=?',t.id);
 assert.equal(queue.enqueueApprovedApproaches({leadIds:cases.map(x=>x.id),approve:true,operatorApproved:true}).status,403);
 delete process.env.PROSPECTOR_OWNER_PHONE;
});
test('greeting uses Sao Paulo day period and cleans the recipient name',async()=>{
 const {greetingForProspect}=await import('../dashboard/prospecting-introduction.mjs');
 assert.equal(greetingForProspect({name:'Ana'},new Date('2026-10-30T12:00:00Z')),'Olá, Ana, bom dia! Tudo bem?');
 assert.match(greetingForProspect({business:'Empresa'},new Date('2026-10-30T19:00:00Z')),/boa tarde/);
 assert.match(greetingForProspect({business:'Empresa'},new Date('2026-10-30T23:00:00Z')),/boa noite/);
});
