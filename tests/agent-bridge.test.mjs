import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
process.env.PROSPECTOR_DATA_DIR=fs.mkdtempSync(path.join(os.tmpdir(),'prospector-ai-bridge-'));
const here=path.dirname(fileURLToPath(import.meta.url));
const manifest=JSON.parse(fs.readFileSync(path.join(here,'../bridge/campaigns/consecom-350.json'),'utf8'));
const bridge=await import('../dashboard/agent-bridge.mjs');
const db=await import('../dashboard/db.mjs');
test('public GitHub bridge manifest is strictly validated and forbids unsafe settings',()=>{
 const m=bridge.validateAgentManifest(manifest);
 assert.equal(m.intro,manifest.campaign.initial_message);
 assert.equal(m.before,45);
 assert.equal(m.after,10);
 assert.equal(m.audioHash,'9e0b22e2c1aeb6707099488f3ae961cc9e2dcf30c9f8c73b300dbe832783f091');
 const bad=structuredClone(manifest);
 bad.safeguards.requires_contact_permission=false;
 assert.throws(()=>bridge.validateAgentManifest(bad),/proteção/);
 bad.safeguards.requires_contact_permission=true;
 bad.campaign.initial_message='Sem saudação personalizada';
 assert.throws(()=>bridge.validateAgentManifest(bad),/saudação/);
 bad.campaign.initial_message=manifest.campaign.initial_message;
 bad.campaign.interested_action='run_shell';
 assert.throws(()=>bridge.validateAgentManifest(bad),/Kanban/);
});
test('sync creates one disabled workflow, never unpauses or starts auto outreach without media',()=>{
 db.setSetting('paused',true);
 db.setSetting('auto_initial',false);
 const result=bridge.reconcileAgentManifest(manifest);
 assert.equal(result.state,'WAITING_MEDIA');
 assert.equal(result.ready,false);
 assert.equal(db.getSetting('paused'),true);
 assert.equal(db.getSetting('auto_initial'),false);
 const w=db.one('SELECT * FROM workflows WHERE id=?',result.workflowId);
 assert.equal(w.enabled,0);
 const s=JSON.parse(w.steps);
 assert.deepEqual(s.map(x=>x.type),['message','wait_reply','delay','audio','delay','video','wait_reply','decision','end']);
 assert.equal(s[2].seconds,45);
 assert.equal(s[4].seconds,10);
 assert.equal(s[5].caption,'O que achou? Gostaria de ter um assim também?');
 assert.equal(s[7].yes_action,'handover');
 assert.equal(db.all('SELECT * FROM jobs').length,0);
});
test('same manifest is idempotent; new revision edits the same workflow',()=>{
 const first=bridge.reconcileAgentManifest(manifest);
 const before=db.one('SELECT * FROM workflows WHERE id=?',first.workflowId);
 const repeat=bridge.reconcileAgentManifest(manifest);
 const after=db.one('SELECT * FROM workflows WHERE id=?',repeat.workflowId);
 assert.equal(first.workflowId,repeat.workflowId);
 assert.equal(before.version,after.version);
 const version2=structuredClone(manifest);
 version2.revision=2;
 version2.campaign.video_caption='O que achou? Gostaria de ter um site profissional assim também?';
 const updated=bridge.reconcileAgentManifest(version2);
 const w=db.one('SELECT * FROM workflows WHERE id=?',updated.workflowId);
 assert.equal(w.id,first.workflowId);
 assert.equal(w.version,before.version+1);
 assert.equal(JSON.parse(w.steps)[5].caption,version2.campaign.video_caption);
});
test('bridge will not edit an active operation',()=>{
 db.setSetting('paused',false);
 const original=bridge.bridgeStatus();
 const r=bridge.reconcileAgentManifest(manifest);
 assert.equal(r.state,'PAUSED_REQUIRED');
 assert.equal(db.getSetting('paused'),false);
 const w=db.one('SELECT * FROM workflows WHERE id=?',original.workflowId);
 assert.equal(JSON.parse(w.steps)[5].caption,'O que achou? Gostaria de ter um site profissional assim também?');
});
test('AI bridge exposes only bounded, preapproved endpoints',()=>{
 const spec=bridge.bridgeSpec();
 assert.equal(spec.methods.uploadPackage.contentType,'application/zip');
 assert.equal(spec.methods.sync.auth,'admin_session');
 assert.equal(spec.constraints.neverUnpause,true);
 assert.equal(spec.constraints.requiresConsent,true);
});